#!/usr/bin/env node
/**
 * Writes assets/data/mutashabihat/nourquran_hafiz_excluded_cards.json: the similar-verse cards the
 * app does not offer because the Similar tails card of the same ayah asks the same answer
 * (sameAnswerAsTail in lib/fsrs/similar-card-text.ts, which also splits the tails and builds the
 * fronts, so the list follows the cards the app shows).
 *
 * usage: node scripts/build-similar-card-exclusions.mjs [--report]
 *
 * Reads the shipped rows (assets/data/mutashabihat/nourquran_hafiz_rows.json) and the Quran text
 * (assets/data/quran-data.json) read only. Rerun it whenever the rows change;
 * tests/unit/similar-card-exclusions.test.ts fails while the list is stale. --report prints each
 * excluded card with both answers.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(import.meta.dirname, "..");
const ROWS_PATH = path.join(ROOT, "assets", "data", "mutashabihat", "nourquran_hafiz_rows.json");
const QURAN_PATH = path.join(ROOT, "assets", "data", "quran-data.json");
const OUT_PATH = path.join(ROOT, "assets", "data", "mutashabihat", "nourquran_hafiz_excluded_cards.json");
const ABOUT =
  "Generated by scripts/build-similar-card-exclusions.mjs. Study card ids of similar-verse cards the app does not offer because the Similar tails card of the same ayah asks the same answer. Do not edit.";

// The app's modules import each other through the "@/" alias, which Node does not know.
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (!specifier.startsWith("@/")) return nextResolve(specifier, context);
    return nextResolve(pathToFileURL(path.join(ROOT, `${specifier.slice(2)}.ts`)).href, context);
  },
});
const { excludedSimilarCards } = await import("../lib/fsrs/similar-card-text.ts");

const rowsFile = JSON.parse(readFileSync(ROWS_PATH, "utf8"));
const quranText = JSON.parse(readFileSync(QURAN_PATH, "utf8")).tables.quran_text;
const ayat = new Map(
  quranText.map((row) => [`${row.surah}:${row.ayah}`, { textUthmani: row.text_uthmani, textClean: row.text_clean }]),
);

// Row columns as lib/database/mutashabihat-rows.ts reads them.
const rows = {
  groups: rowsFile.groups.map(([id, kind, cue]) => ({ id, kind, cue })),
  refs: rowsFile.refs.map(([groupId, sortOrder, surah, ayah, , tail5, preText, similarText]) => ({
    groupId,
    sortOrder,
    surah,
    ayah,
    tail5,
    preText,
    similarText,
  })),
};

const excluded = excludedSimilarCards(rows, (surah, ayah) => ayat.get(`${surah}:${ayah}`));
const cards = excluded.map((card) => card.id);
writeFileSync(OUT_PATH, `${JSON.stringify({ about: ABOUT, cards }, null, 2)}\n`);
console.log(
  `Wrote ${cards.length} excluded cards from rows version ${rowsFile.version} to ${path.relative(ROOT, OUT_PATH)}`,
);

if (process.argv.includes("--report")) {
  for (const card of excluded) {
    console.log(`${card.surah}:${card.ayah}\t${card.id}\t${card.restUthmani}\t${card.tailId}\t${card.tailUthmani}`);
  }
}
