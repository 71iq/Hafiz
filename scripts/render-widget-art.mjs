// Packages the Zayt widget art into Android resources.
// Usage: node scripts/render-widget-art.mjs /path/to/studio/zayt/widget/out
// The source is the studio's widget export (branch feat/zayt-widget-art, zayt/widget/README.md). It
// holds res/drawable-nodpi/*.webp with the final names, and clips.json with each clip's frames as
// { "done": [{ "file": "hafiz_widget_zayt_done_00.webp", "durationMs": 110 }, ...], ... }.
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("Pass the studio's zayt/widget/out directory.");
const res = fileURLToPath(new URL("../android/app/src/main/res/", import.meta.url));
const art = path.join(res, "drawable-nodpi");
const drawable = path.join(res, "drawable");
const layout = path.join(res, "layout");

/** Poses with a slow-blink frame (WidgetArt.blink). Seated and celebrating stills have none. */
const BLINKING = ["rest", "warm", "wave", "glow", "open", "glow_halo", "open_halo", "warm_halo"];
/** One-shot clips by resource name: the export's clip and the still it ends on (WidgetArt.celebration). */
const CLIPS = {
  done: ["done", "shimmer"],
  done_halo: ["done_halo", "shimmer_halo"],
  milestone: ["turn", "milestone"],
};
/**
 * Open eyes, then the studio's slow blink of a quarter second (Zayt spec 5.6). Two unequal gaps keep
 * the loop from reading as a metronome.
 */
const BLINK = [
  ["open", 4200],
  ["blink", 250],
  ["open", 6100],
  ["blink", 250],
];

const header = (comment) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${comment} Generated by scripts/render-widget-art.mjs. -->\n`;
const list = (comment, oneshot, frames) =>
  header(comment) +
  `<animation-list xmlns:android="http://schemas.android.com/apk/res/android" android:oneshot="${oneshot}">\n` +
  frames.map(([name, ms]) => `    <item android:drawable="@drawable/${name}" android:duration="${ms}"/>`).join("\n") +
  "\n</animation-list>\n";
// An indeterminate ProgressBar is the one RemoteViews view that runs a frame list on the host. Its
// 1 dp maximum keeps the frames from sizing the art box; the box wraps the still, and FrameLayout's
// second measure then gives the bar exactly the still's size.
const motion = (comment, drawableName) =>
  header(comment) +
  `<ProgressBar xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:minWidth="0dp"
    android:minHeight="0dp"
    android:maxWidth="1dp"
    android:maxHeight="1dp"
    android:indeterminateOnly="true"
    android:indeterminate="true"
    android:indeterminateTint="@null"
    android:indeterminateDrawable="@drawable/${drawableName}"
    android:importantForAccessibility="no"/>
`;

// Replace the previous export entirely, so renamed or dropped frames do not linger.
await mkdir(art, { recursive: true });
for (const file of await readdir(art)) {
  if (/^hafiz_widget_(zayt|scene)_/.test(file)) await rm(path.join(art, file));
}
for (const dir of [drawable, layout]) {
  for (const file of await readdir(dir)) {
    if (/^hafiz_widget_(anim|motion)_/.test(file) || file === "hafiz_widget_milestone_motion.xml")
      await rm(path.join(dir, file));
  }
}
const exported = path.join(source, "res", "drawable-nodpi");
const files = (await readdir(exported)).filter((file) => /^hafiz_widget_(zayt|scene)_[a-z0-9_]+\.webp$/.test(file));
for (const file of files) await copyFile(path.join(exported, file), path.join(art, file));
const names = new Set(files.map((file) => file.replace(/\.webp$/, "")));
const need = (name) => {
  if (!names.has(name)) throw new Error(`The export has no ${name}.webp`);
  return name;
};

for (const pose of BLINKING) {
  const frames = BLINK.map(([kind, ms]) => [need(`hafiz_widget_zayt_${pose}${kind === "blink" ? "_blink" : ""}`), ms]);
  await writeFile(
    path.join(drawable, `hafiz_widget_anim_blink_${pose}.xml`),
    list(`Zayt's idle slow blink, ${pose}.`, false, frames),
  );
  await writeFile(
    path.join(layout, `hafiz_widget_motion_blink_${pose}.xml`),
    motion(`Runs hafiz_widget_anim_blink_${pose} on the launcher.`, `hafiz_widget_anim_blink_${pose}`),
  );
}

const clips = JSON.parse(await readFile(path.join(source, "clips.json"), "utf8"));
for (const [clip, [exported, still]] of Object.entries(CLIPS)) {
  const frames = clips[exported];
  if (!Array.isArray(frames) || frames.length < 2) throw new Error(`clips.json has no frames for ${exported}`);
  const items = frames.map(({ file, durationMs }) => [need(file.replace(/\.webp$/, "")), durationMs]);
  // The last drawing is the entry's own still, so the hand-over to the blink cannot jump.
  items[items.length - 1][0] = need(`hafiz_widget_zayt_${still}`);
  await writeFile(path.join(drawable, `hafiz_widget_anim_${clip}.xml`), list(`One-shot ${clip} clip.`, true, items));
  await writeFile(
    path.join(layout, `hafiz_widget_motion_${clip}.xml`),
    motion(`Plays hafiz_widget_anim_${clip} once on the launcher.`, `hafiz_widget_anim_${clip}`),
  );
}
console.log(
  `Copied ${files.length} files; wrote ${BLINKING.length} blink loops and ${Object.keys(CLIPS).length} clips.`,
);

// Streak flames: the export's SVGs become VectorDrawables. They use only filled paths, an evenodd
// rule and user-space linear gradients, which VectorDrawable draws the same way.
const flameSource = path.join(source, "flame");
const svg = (name) => readFile(path.join(flameSource, `${name}.svg`), "utf8");
const attr = (tag, name) => new RegExp(`\\b${name}="([^"]*)"`).exec(tag)?.[1];
const argb = (hex, opacity = 1) =>
  `#${Math.round(opacity * 255)
    .toString(16)
    .padStart(2, "0")
    .toUpperCase()}${hex.replace("#", "").toUpperCase()}`;

function vector(comment, body, aapt = false) {
  return (
    header(comment) +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"${aapt ? ' xmlns:aapt="http://schemas.android.com/aapt"' : ""}\n` +
    '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n' +
    body +
    "</vector>\n"
  );
}

function linear(gradient) {
  const stops = [...gradient.matchAll(/<stop\b[^>]*>/g)].map(([stop]) => [
    attr(stop, "offset") ?? "0",
    argb(attr(stop, "stop-color"), Number(attr(stop, "stop-opacity") ?? 1)),
  ]);
  const [x1, y1, x2, y2] = ["x1", "y1", "x2", "y2"].map((name) => attr(gradient, name));
  return (
    '    <aapt:attr name="android:fillColor">\n' +
    `      <gradient android:type="linear" android:startX="${x1}" android:startY="${y1}" android:endX="${x2}" android:endY="${y2}">\n` +
    stops
      .map(([offset, color]) => `        <item android:offset="${Number(offset)}" android:color="${color}"/>\n`)
      .join("") +
    "      </gradient>\n    </aapt:attr>\n"
  );
}

/** Converts one export SVG. `fill` replaces solid colors, for the single-color flames. */
function convert(text, fill) {
  const gradients = new Map(
    [...text.matchAll(/<linearGradient\b[^>]*>[\s\S]*?<\/linearGradient>/g)].map(([gradient]) => [
      attr(gradient, "id"),
      gradient,
    ]),
  );
  let body = "";
  for (const [tag] of text.matchAll(/<path\b[^>]*>/g)) {
    const color = attr(tag, "fill");
    const rule = attr(tag, "fill-rule") === "evenodd" ? ' android:fillType="evenOdd"' : "";
    const data = attr(tag, "d");
    const url = /^url\(#(.+)\)$/.exec(color)?.[1];
    body += url
      ? `  <path android:pathData="${data}"${rule}>\n${linear(gradients.get(url))}  </path>\n`
      : `  <path android:fillColor="${fill ?? argb(color, Number(attr(tag, "fill-opacity") ?? 1))}"${rule} android:pathData="${data}"/>\n`;
  }
  return { body, aapt: gradients.size > 0 };
}

const glow = (cx, cy, r, color) =>
  `  <path android:pathData="M${cx - r},${cy}a${r},${r} 0,1 0,${2 * r},0a${r},${r} 0,1 0,${-2 * r},0Z">\n` +
  '    <aapt:attr name="android:fillColor">\n' +
  `      <gradient android:type="radial" android:centerX="${cx}" android:centerY="${cy}" android:gradientRadius="${r}">\n` +
  `        <item android:offset="0" android:color="${color}"/>\n        <item android:offset="1" android:color="#00FFC34D"/>\n` +
  "      </gradient>\n    </aapt:attr>\n  </path>\n";

const STAGES = ["under 7 days", "7 days", "14 days", "30 days", "50 days", "100 days", "365 days"];
for (const [tier, stage] of STAGES.entries()) {
  const { body } = convert(await svg(`flame_lit_t${tier}`));
  // From 14 days a warm glow sits behind the flame, so each stage differs at 18 dp, not only in tint.
  const halo =
    tier >= 2 ? glow(12, 14.5, 11, ["#59FFC34D", "#66FFC34D", "#73FFC34D", "#80FFC34D", "#99FFC34D"][tier - 2]) : "";
  await writeFile(
    path.join(drawable, `hafiz_widget_flame_lit_t${tier}.xml`),
    vector(`Lit streak flame, stage ${tier} (${stage}).`, halo + body, true),
  );
}
// The outline comes from the export's empty flame. The waiting flame adds the white-hot core of the
// last stage as its ember. The System theme's default colors follow the launcher's day or night.
const outline = convert(await svg("flame_out"), "@color/hafiz_widget_text_secondary").body;
const ember = [...(await svg("flame_lit_t6")).matchAll(/<path\b[^>]*>/g)].at(-1)[0];
const emberData = attr(ember, "d");
await writeFile(
  path.join(drawable, "hafiz_widget_flame_out.xml"),
  vector("No streak yet: the outline alone.", outline),
);
await writeFile(
  path.join(drawable, "hafiz_widget_flame_unlit.xml"),
  vector(
    "Streak alive, today not done yet: the outline with an ember.",
    outline.replace("@color/hafiz_widget_text_secondary", "@color/hafiz_widget_accent") +
      `  <path android:fillColor="@color/hafiz_widget_accent" android:pathData="${emberData}"/>\n`,
  ),
);
// The night skies' ember loop, drawn in white ink with a warm ember (hafiz_widget_flame_ember_loop).
const white = outline.replace("@color/hafiz_widget_text_secondary", "#FFFFFFFF");
await writeFile(
  path.join(drawable, "hafiz_widget_flame_ember_dim.xml"),
  vector(
    "The waiting flame on a night sky, ember low.",
    white + `  <path android:fillColor="#CCF59E2B" android:pathData="${emberData}"/>\n`,
  ),
);
await writeFile(
  path.join(drawable, "hafiz_widget_flame_ember_bright.xml"),
  vector(
    "The waiting flame on a night sky, ember glowing.",
    glow(12.2, 17.6, 6.5, "#80FFB547") +
      white +
      `  <path android:fillColor="#FFFFC45C" android:pathData="${emberData}"/>\n`,
    true,
  ),
);
console.log("Wrote the streak flames.");
